// Writes test/screens/support/pseudo_l10n.g.dart: for every module's
// generated strings class, a subclass that returns each English string in
// pseudo-locale form. Run from apps/ferret after any ARB change:
//
//   dart run tool/pseudo_l10n.dart
import 'dart:io';

void main() {
  final modules = Directory('../../modules');
  final classes = <({String module, String name, String file, String body})>[];

  final folders = modules.listSync().whereType<Directory>().toList()
    ..sort((left, right) => left.path.compareTo(right.path));
  for (final folder in folders) {
    final module = folder.uri.pathSegments
        .where((part) => part.isNotEmpty)
        .last;
    final generated = Directory('${folder.path}/lib/l10n/generated');
    if (!generated.existsSync()) {
      continue;
    }

    final base = generated
        .listSync()
        .whereType<File>()
        .map((file) => file.uri.pathSegments.last)
        .where((name) => name.endsWith('_localizations.dart'))
        .firstOrNull;
    if (base == null) {
      continue;
    }

    final source = File('${generated.path}/$base').readAsStringSync();
    final className = RegExp(
      r'abstract class (\w+Localizations) ',
    ).firstMatch(source)?.group(1);
    if (className == null) {
      continue;
    }

    classes.add((
      module: module,
      name: className,
      file: base.replaceAll('.dart', ''),
      body: _overrides(source),
    ));
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/pseudo_l10n.dart. Do not edit.')
    ..writeln('// ignore_for_file: type=lint, depend_on_referenced_packages')
    ..writeln()
    ..writeln("import 'package:flutter/foundation.dart';")
    ..writeln("import 'package:flutter/widgets.dart';");
  for (final entry in classes) {
    out.writeln(
      "import 'package:${entry.module}/l10n/generated/${entry.file}_en.dart';",
    );
    out.writeln(
      "import 'package:${entry.module}/l10n/generated/${entry.file}.dart';",
    );
  }

  out
    ..writeln()
    ..writeln("import 'pseudo_text.dart';")
    ..writeln()
    ..writeln('/// One delegate per module, each giving pseudo strings.')
    ..writeln('List<LocalizationsDelegate<Object?>> pseudoDelegates() => [');
  for (final entry in classes) {
    out.writeln('  _PseudoDelegate<${entry.name}>(Pseudo${entry.name}.new),');
  }

  out
    ..writeln('];')
    ..writeln()
    ..writeln('class _PseudoDelegate<T> extends LocalizationsDelegate<T> {')
    ..writeln('  const _PseudoDelegate(this._create);')
    ..writeln()
    ..writeln('  final T Function() _create;')
    ..writeln()
    ..writeln('  @override')
    ..writeln('  bool isSupported(Locale locale) => true;')
    ..writeln()
    ..writeln('  @override')
    ..writeln(
      '  Future<T> load(Locale locale) => SynchronousFuture(_create());',
    )
    ..writeln()
    ..writeln('  @override')
    ..writeln('  bool shouldReload(_PseudoDelegate<T> old) => false;')
    ..writeln('}');
  for (final entry in classes) {
    out
      ..writeln()
      ..writeln('class Pseudo${entry.name} extends ${entry.name}En {')
      ..write(entry.body)
      ..writeln('}');
  }

  File('test/screens/support/pseudo_l10n.g.dart').writeAsStringSync('$out');
  stdout.writeln('${classes.length} modules');
}

String _overrides(String source) {
  final out = StringBuffer();
  for (final match in RegExp(
    r'^  String get (\w+);',
    multiLine: true,
  ).allMatches(source)) {
    final name = match.group(1);
    out
      ..writeln('  @override')
      ..writeln('  String get $name => pseudo(super.$name);');
  }

  for (final match in RegExp(
    r'^  String (\w+)\(([^)]*)\);',
    multiLine: true,
    dotAll: true,
  ).allMatches(source)) {
    final name = match.group(1);
    final parameters = (match.group(2) ?? '')
        .split(',')
        .map((part) => part.trim())
        .where((part) => part.isNotEmpty)
        .toList();
    final names = [for (final part in parameters) part.split(' ').last];
    out
      ..writeln('  @override')
      ..writeln('  String $name(${parameters.join(', ')}) =>')
      ..writeln('      pseudo(super.$name(${names.join(', ')}));');
  }

  return '$out';
}
