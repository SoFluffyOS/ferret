import Cocoa
import FlutterMacOS

/// Reads and writes NSPasteboard and reports changes by watching its
/// changeCount, which is the only change signal macOS offers.
public class FerretClipboardPlugin: NSObject, FlutterPlugin, ClipboardHostApi {
  /// Password managers add these types so clipboard tools leave secrets alone
  /// (see nspasteboard.org).
  private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
  private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")

  /// Marks content an app put there without the person copying anything.
  /// The watcher doesn't report it; asked for, it is still read.
  private static let autoGeneratedType = NSPasteboard.PasteboardType(
    "org.nspasteboard.AutoGeneratedType")

  /// The two above, and older private or momentary markers some password
  /// managers and text expanders still use.
  private static let privateTypes: Set<NSPasteboard.PasteboardType> = [
    concealedType,
    transientType,
    NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    NSPasteboard.PasteboardType("net.antelle.keeweb"),
    NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    NSPasteboard.PasteboardType("com.typeit4me.clipping"),
    NSPasteboard.PasteboardType("Pasteboard generator type"),
  ]

  /// Password managers whose copies count as private even when they don't
  /// mark them: the app in front when the copy is read.
  private static let passwordApps: Set<String> = [
    "com.apple.Passwords",
    "com.apple.keychainaccess",
    "com.1password.1password",
    "com.agilebits.onepassword7",
    "com.agilebits.onepassword-osx",
    "com.bitwarden.desktop",
    "org.keepassxc.keepassxc",
    "com.lastpass.LastPass",
    "in.sinew.Enpass-Desktop",
    "me.proton.pass.electron",
  ]
  private static let watchInterval: TimeInterval = 0.5

  private let pasteboard = NSPasteboard.general
  private let flutterApi: ClipboardFlutterApi
  private var timer: Timer?
  private var lastChangeCount: Int

  init(flutterApi: ClipboardFlutterApi) {
    self.flutterApi = flutterApi
    lastChangeCount = NSPasteboard.general.changeCount
  }

  public static func register(with registrar: FlutterPluginRegistrar) {
    let instance = FerretClipboardPlugin(
      flutterApi: ClipboardFlutterApi(binaryMessenger: registrar.messenger))
    ClipboardHostApiSetup.setUp(binaryMessenger: registrar.messenger, api: instance)
  }

  func read() throws -> PlatformClip? {
    let types = pasteboard.types ?? []
    let sensitive = !Self.privateTypes.isDisjoint(with: types) || Self.passwordAppInFront()

    let files = copiedFiles()
    if let text = pasteboard.string(forType: .string), !text.isEmpty {
      return PlatformClip(
        text: text, sensitive: sensitive, filePaths: files.isEmpty ? nil : files)
    }

    if !files.isEmpty {
      let names = files.map { ($0 as NSString).lastPathComponent }.joined(separator: "\n")
      return PlatformClip(text: names, sensitive: sensitive, filePaths: files)
    }

    if let png = pasteboard.data(forType: .png) {
      return PlatformClip(
        image: FlutterStandardTypedData(bytes: png), imageMime: "image/png", sensitive: sensitive)
    }

    if let tiff = pasteboard.data(forType: .tiff),
      let bitmap = NSBitmapImageRep(data: tiff),
      let png = bitmap.representation(using: .png, properties: [:])
    {
      return PlatformClip(
        image: FlutterStandardTypedData(bytes: png), imageMime: "image/png", sensitive: sensitive)
    }

    return nil
  }

  private static func passwordAppInFront() -> Bool {
    guard let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier else {
      return false
    }

    return passwordApps.contains(app)
  }

  /// Files copied in Finder, by their paths.
  private func copiedFiles() -> [String] {
    let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
    let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: options) as? [URL]
    return (urls ?? []).map(\.path)
  }

  func write(clip: PlatformClip) throws {
    pasteboard.clearContents()

    if let text = clip.text {
      pasteboard.setString(text, forType: .string)
    } else if let image = clip.image {
      let data = image.data
      if clip.imageMime == "image/png" {
        pasteboard.setData(data, forType: .png)
      }
      if let tiff = NSImage(data: data)?.tiffRepresentation {
        pasteboard.setData(tiff, forType: .tiff)
      }
    }

    if clip.sensitive {
      pasteboard.setData(Data(), forType: Self.concealedType)
    }

    lastChangeCount = pasteboard.changeCount
  }

  func startWatching() throws {
    guard timer == nil else {
      return
    }

    lastChangeCount = pasteboard.changeCount
    let timer = Timer(timeInterval: Self.watchInterval, repeats: true) { [weak self] _ in
      self?.checkForChange()
    }
    timer.tolerance = Self.watchInterval / 2
    RunLoop.main.add(timer, forMode: .common)
    self.timer = timer
  }

  func stopWatching() throws {
    timer?.invalidate()
    timer = nil
  }

  private func checkForChange() {
    let changeCount = pasteboard.changeCount
    guard changeCount != lastChangeCount else {
      return
    }

    lastChangeCount = changeCount
    if pasteboard.types?.contains(Self.autoGeneratedType) == true {
      return
    }

    Task { @MainActor [flutterApi] in
      try? await flutterApi.onChanged()
    }
  }
}
